/**
 * The extensibility contract issue #1512 exists for: every kind the engine's
 * `GET /elements/kinds` serves must be *editable*, whether or not
 * `elementForms.ts` has ever heard of it. A kind with no bespoke override
 * falls through to the schema-driven `GenericElementForm`, so the app never
 * crashes on, or silently drops, a kind it has never seen.
 *
 * `engine/tests/fixtures/element-kinds.json` is not hand-maintained - it is
 * written by `elements_registry_test.cpp` on every engine test run, straight
 * off the live registry - so this reads it the same way the other
 * `*.conformance.test.ts` files read their engine fixtures. Held in
 * `ENGINE_READING_GUARDS` (`@/lib/routed-inputs.testkit`) so CI routes an edit
 * to the fixture back to this suite.
 *
 * This does **not** assert every kind needs a bespoke form - most legitimately
 * do not - only that the catalogue's current shape renders, for every kind,
 * without throwing and without silently producing an empty row.
 */

